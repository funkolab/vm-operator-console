/**
 * Generates Zod schemas and field documentation from the vm-operator CRDs.
 *
 * Usage: bun scripts/gen-crd-schemas.ts [operatorDir]
 * Source: <operatorDir>/config/crd/bases/*.yaml
 * Output: packages/shared/src/crd/generated.ts, packages/shared/src/crd/docs.generated.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { parse } from "yaml";

type JSONSchema = {
  type?: string;
  description?: string;
  properties?: Record<string, JSONSchema>;
  required?: string[];
  items?: JSONSchema;
  additionalProperties?: JSONSchema | boolean;
  enum?: unknown[];
  pattern?: string;
  minLength?: number;
  maxLength?: number;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  format?: string;
  anyOf?: JSONSchema[];
  allOf?: JSONSchema[];
  "x-kubernetes-int-or-string"?: boolean;
  "x-kubernetes-preserve-unknown-fields"?: boolean;
};

const root = resolve(import.meta.dir, "..");
const operatorDir = resolve(process.argv[2] ?? process.env.OPERATOR_DIR ?? join(root, "../vm-operator"));
const crdDir = join(operatorDir, "config/crd/bases");

const docs: Record<string, string> = {};

function isIntOrString(s: JSONSchema): boolean {
  if (s["x-kubernetes-int-or-string"]) return true;
  const types = s.anyOf?.map((a) => a.type).sort();
  return types?.length === 2 && types[0] === "integer" && types[1] === "string";
}

function toZod(s: JSONSchema, path: string, depth: number): string {
  if (s.description && path) docs[path] = s.description.trim();
  const pad = "  ".repeat(depth);
  if (isIntOrString(s)) {
    let str = "z.string()";
    if (s.maxLength !== undefined) str += `.max(${s.maxLength})`;
    return `z.union([z.number(), ${str}])`;
  }
  switch (s.type) {
    case "object": {
      if (s.properties) {
        const req = new Set(s.required ?? []);
        const fields = Object.entries(s.properties).map(([k, v]) => {
          const inner = toZod(v, `${path}/${k}`, depth + 1);
          return `${pad}  ${JSON.stringify(k)}: ${inner}${req.has(k) ? "" : ".optional()"},`;
        });
        return `z.looseObject({\n${fields.join("\n")}\n${pad}})`;
      }
      if (s.additionalProperties && typeof s.additionalProperties === "object") {
        return `z.record(z.string(), ${toZod(s.additionalProperties, `${path}/*`, depth)})`;
      }
      return "z.record(z.string(), z.unknown())";
    }
    case "array": {
      let out = `z.array(${s.items ? toZod(s.items, `${path}/*`, depth) : "z.unknown()"})`;
      if (s.minItems !== undefined) out += `.min(${s.minItems})`;
      if (s.maxItems !== undefined) out += `.max(${s.maxItems})`;
      return out;
    }
    case "string": {
      if (s.enum) return `z.enum(${JSON.stringify(s.enum)})`;
      let out = "z.string()";
      if (s.minLength !== undefined) out += `.min(${s.minLength})`;
      if (s.maxLength !== undefined) out += `.max(${s.maxLength})`;
      if (s.pattern) out += `.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
      return out;
    }
    case "integer": {
      let out = "z.number().int()";
      if (s.minimum !== undefined) out += `.min(${s.minimum})`;
      if (s.maximum !== undefined) out += `.max(${s.maximum})`;
      return out;
    }
    case "number":
      return "z.number()";
    case "boolean":
      return "z.boolean()";
    default:
      return "z.unknown()";
  }
}

const out: string[] = ["// Code generated by scripts/gen-crd-schemas.ts from the vm-operator CRDs. DO NOT EDIT.", 'import { z } from "zod";', ""];
const meta: string[] = [];

for (const file of readdirSync(crdDir)
  .filter((f) => f.endsWith(".yaml"))
  .sort()) {
  const crd = parse(readFileSync(join(crdDir, file), "utf8"));
  const kind: string = crd.spec.names.kind;
  const version = crd.spec.versions.find((v: { storage?: boolean }) => v.storage) ?? crd.spec.versions[0];
  const schema: JSONSchema = version.schema.openAPIV3Schema;
  for (const part of ["spec", "status"] as const) {
    const sub = schema.properties?.[part];
    if (!sub) continue;
    const name = `${kind}${part[0]?.toUpperCase()}${part.slice(1)}Schema`;
    out.push(`export const ${name} = ${toZod(sub, `${kind}/${part}`, 0)};`, "");
  }
  meta.push(
    `  ${kind}: { group: ${JSON.stringify(crd.spec.group)}, version: ${JSON.stringify(version.name)}, plural: ${JSON.stringify(crd.spec.names.plural)}, kind: ${JSON.stringify(kind)} },`,
  );
}
out.push(`export const crdInfo = {\n${meta.join("\n")}\n} as const;`, "");

const outDir = join(root, "packages/shared/src/crd");
writeFileSync(join(outDir, "generated.ts"), out.join("\n"));
writeFileSync(
  join(outDir, "docs.generated.ts"),
  `// Code generated by scripts/gen-crd-schemas.ts from the vm-operator CRDs. DO NOT EDIT.\nexport const fieldDocs: Record<string, string> = ${JSON.stringify(docs, null, 2)};\n`,
);
console.log(`Generated schemas from ${crdDir} (${Object.keys(docs).length} documented fields)`);
